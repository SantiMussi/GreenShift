export const LON0 = -63.5;
export const LAT0 = -35.5;
const K = 0.52;
const KX = K * Math.cos((35 * Math.PI) / 180);

/** Proyección equirectangular simple → coordenadas de escena (x, z). Norte = -z. */
export function project(lon: number, lat: number): [number, number] {
  return [(lon - LON0) * KX, -(lat - LAT0) * K];
}

export function pointInPolygon(x: number, z: number, poly: [number, number][]) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, zi] = poly[i];
    const [xj, zj] = poly[j];
    if (zi > z !== zj > z && x < ((xj - xi) * (z - zi)) / (zj - zi) + xi) inside = !inside;
  }
  return inside;
}
